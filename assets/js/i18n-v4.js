  var STORAGE_KEY = 'gifmp4_lang';
  var CACHE_KEY = 'gifmp4_ip_lang';
  var current = 'en';

  function detectByIP(cb) {
    // Called once; caches result for 24h.
    try {
      var cached = localStorage.getItem(CACHE_KEY);
      if (cached) {
        var c = JSON.parse(cached);
        if (c && c.t && Date.now() - c.t < 86400000) { apply(c.lang); return; }
      }
    } catch (e) {}
    var ctrl = new AbortController();
    var timer = setTimeout(function () { ctrl.abort(); apply('en'); }, 3000);
    fetch('https://ipapi.co/country/', { signal: ctrl.signal })
      .then(function (r) { return r.text(); })
      .then(function (code) {
        clearTimeout(timer);
        var lang = mapCountry(code);
        try { localStorage.setItem(CACHE_KEY, JSON.stringify({ t: Date.now(), lang: lang })); } catch (e) {}
        apply(lang);
      })
      .catch(function () { clearTimeout(timer); apply('en'); });
  }

  function mapCountry(code) {
    code = (code || '').trim().toUpperCase();
    if (!code) return 'en';
    if (code === 'CN') return 'zh-CN';
    if (code === 'HK' || code === 'MO' || code === 'TW') return 'zh-TW';
    if (code === 'JP') return 'ja';
    if (code === 'KR') return 'ko';
    if (code === 'ES' || code === 'MX' || code === 'AR' || code === 'CO' || code === 'CL' || code === 'PE' || code === 'VE') return 'es';
    if (code === 'FR') return 'fr';
    if (code === 'DE' || code === 'AT' || code === 'CH') return 'de';
    if (code === 'BR' || code === 'PT') return 'pt';
    return 'en';
  }

  function t(key, vars) {
    var dict = translations[current] || {};
    var s = dict[key] !== undefined ? dict[key] : base[key];
    if (s === undefined) s = key;
    if (vars) {
      for (var k in vars) s = s.replace('{' + k + '}', vars[k]);
    }
    return s;
  }

  function apply(lang) {
    if (!translations[lang]) lang = 'en';
    current = lang;
    document.documentElement.lang = lang === 'en' ? 'en' : lang;
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var k = el.getAttribute('data-i18n');
      if (translations[lang][k] !== undefined || base[k] !== undefined) {
        el.textContent = t(k);
      }
    }
    var selects = document.querySelectorAll('[data-i18n-lang]');
    for (var j = 0; j < selects.length; j++) {
      var sel = selects[j];
      var name = sel.getAttribute('data-i18n-lang');
      if (sel.options && sel.options[name] !== undefined) sel.value = name;
      else if (sel.tagName === 'SPAN' || sel.tagName === 'DIV') sel.textContent = name;
    }
    var langSelector = document.getElementById('langSelector');
    if (langSelector) langSelector.value = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    // page-specific re-render hooks
    if (window.GIFMP4OnLangChange) window.GIFMP4OnLangChange(lang);
  }

  function init() {
    var saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) {}
    if (saved && translations[saved]) {
      apply(saved);
    } else {
      apply('en');
      detectByIP();
    }
  }

  window.GIFMP4I18N = {
    t: t,
    apply: apply,
    init: init,
    current: function () { return current; },
    setLang: function (l) { apply(l); }
  };
